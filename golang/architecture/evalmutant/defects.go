// The baseline is a small, deliberately ordinary service with three layers and
// two domains. It is not meant to be interesting; it is meant to be CLEAN, so
// that every difference a mutant introduces is the defect and nothing else.
//
// Layering is explicit in the prose so a stale-documentation or
// forbidden-dependency mutant has something real to contradict rather than a
// convention a reader has to infer.
func baselineFiles() map[string]string {
	return map[string]string{
		"go.mod": "module example.com/eval\n\ngo 1.22\n",

		"docs/ARCHITECTURE.md": `# Architecture

Three layers, one direction:

    api  ->  service  ->  storage

` + "`storage` never imports `service` or `api`." + `

Two domains, ` + "`billing`" + ` and ` + "`shipping`" + `. A domain reaches another
only through its published surface, never its internals.

Rate limiting is decided in exactly one place: ` + "`service.RateLimit`" + `.
`,

		"api/api.go": `package api

import "example.com/eval/service"

// Handle serves one request.
func Handle(userID string, cost int) bool {
	return service.Allow(userID, cost)
}
`,

		"service/service.go": `package service

import "example.com/eval/storage"

// RateLimit is the single authority on how much one user may spend.
func RateLimit(tier string) int {
	switch tier {
	case "premium":
		return 1000
	case "standard":
		return 100
	default:
		return 10
	}
}

// Allow decides whether a request may proceed.
func Allow(userID string, cost int) bool {
	tier := storage.TierOf(userID)
	return cost <= RateLimit(tier)
}
`,

		"storage/storage.go": `package storage

// TierOf reports a user's billing tier.
func TierOf(userID string) string {
	if userID == "" {
		return "anonymous"
	}
	return "standard"
}
`,

		"billing/billing.go": `package billing

// Charge records a charge against an account.
func Charge(account string, amount int) int {
	return amount
}
`,

		"billing/surface.go": `package billing

// Quote is billing's published surface. Other domains use this.
func Quote(account string, amount int) int {
	return Charge(account, amount)
}
`,

		"shipping/shipping.go": `package shipping

import "example.com/eval/billing"

// Ship quotes a shipment through billing's published surface.
func Ship(account string, weight int) int {
	return billing.Quote(account, weight*2)
}
`,

		"docs/claims.md": `# Governed claims

- claim.rate_limit_single_authority — rate limiting is decided only in
  service.RateLimit. Evidence: evidence/rate_limit_test_report.txt
`,

		"evidence/rate_limit_test_report.txt": "rate limit suite: 4 passed, 0 failed\n",

		"docs/generated/inventory.md": `<!-- GENERATED by tools/gen-inventory — do not edit by hand. -->

- api
- service
- storage
- billing
- shipping
`,

		"docs/obligations.md": `# Proof obligations

- obligation.rate_limit_enforced — status: discharged
  proof: evidence/rate_limit_test_report.txt
`,
	}
}

// mutators introduce exactly one defect each, returning the reference
// statement and the commit message the mutating change would carry.
var mutators = map[Defect]func(map[string]string) (statement, commitMessage string){

	DefectAuthoritySplit: func(f map[string]string) (string, string) {
		// api computes the limit itself instead of asking service. Two owners
		// now answer the same question, and they disagree for premium users.
		f["api/api.go"] = `package api

import "example.com/eval/service"

// localLimit is api's own copy of the rate-limit decision.
func localLimit(tier string) int {
	switch tier {
	case "premium":
		return 500
	case "standard":
		return 100
	default:
		return 10
	}
}

// Handle serves one request.
func Handle(userID string, cost int) bool {
	if cost > localLimit("premium") {
		return false
	}
	return service.Allow(userID, cost)
}
`
		return "api.localLimit independently computes the rate limit that service.RateLimit owns, and returns 500 where service returns 1000; one question now has two authoritative answers",
			"api: add a fast-path limit check"
	},

	DefectForbiddenDependencyDirection: func(f map[string]string) (string, string) {
		// storage imports service, inverting the documented direction.
		f["storage/storage.go"] = `package storage

import "example.com/eval/service"

// TierOf reports a user's billing tier.
func TierOf(userID string) string {
	if userID == "" {
		return "anonymous"
	}
	if service.RateLimit("standard") > 50 {
		return "standard"
	}
	return "restricted"
}
`
		return "storage imports service, inverting the documented api -> service -> storage direction",
			"storage: consult the configured limit when resolving a tier"
	},

	DefectStaleDocumentation: func(f map[string]string) (string, string) {
		// The code moves; the prose does not. The document now states a rule
		// the code contradicts.
		f["service/service.go"] = strings.Replace(
			f["service/service.go"],
			`	case "premium":
		return 1000`,
			`	case "premium":
		return 2500`, 1)
		f["service/service.go"] = strings.Replace(
			f["service/service.go"],
			"// RateLimit is the single authority on how much one user may spend.",
			"// RateLimit is the single authority on how much one user may spend.\n// Premium was raised to 2500 for the enterprise pilot.", 1)
		f["docs/ARCHITECTURE.md"] = strings.Replace(
			f["docs/ARCHITECTURE.md"],
			"Rate limiting is decided in exactly one place: `service.RateLimit`.",
			"Rate limiting is decided in exactly one place: `service.RateLimit`.\nThe premium ceiling is 1000 and has never changed.", 1)
		return "docs/ARCHITECTURE.md asserts the premium ceiling is 1000 and has never changed, while service.RateLimit returns 2500",
			"service: raise the premium ceiling for the enterprise pilot"
	},

	DefectImplementationRepetition: func(f map[string]string) (string, string) {
		// The same trivial clamp appears in three packages. It is duplication,
		// not a law: an investigator that promotes it to an architectural rule
		// has manufactured structure from a maintenance fact.
		clamp := `
// clamp bounds a value to a maximum.
func clamp(v, max int) int {
	if v > max {
		return max
	}
	return v
}
`
		f["api/api.go"] += clamp
		f["service/service.go"] += clamp
		f["storage/storage.go"] += clamp
		return "an identical clamp helper is copied into api, service and storage; this is duplication and must NOT be reported as an architectural rule",
			"chore: add a clamp helper where it is needed"
	},

	DefectMissingEvidenceProvider: func(f map[string]string) (string, string) {
		// The claim cites a report that does not exist.
		delete(f, "evidence/rate_limit_test_report.txt")
		return "claim.rate_limit_single_authority cites evidence/rate_limit_test_report.txt, which does not exist in the tree",
			"docs: record the rate-limit claim"
	},

	DefectMisleadingCommitMessage: func(f map[string]string) (string, string) {
		// The message claims a security fix; the diff only renames a local.
		f["storage/storage.go"] = strings.Replace(
			f["storage/storage.go"],
			"func TierOf(userID string) string {\n\tif userID == \"\" {",
			"func TierOf(id string) string {\n\tuserID := id\n\tif userID == \"\" {", 1)
		return "the commit message claims an authentication bypass was fixed, while the change only renames a parameter",
			"fix: close authentication bypass in tier resolution (CVE-pending)"
	},

	DefectGeneratedFileContamination: func(f map[string]string) (string, string) {
		// A generated inventory is hand-edited. The next regeneration will
		// silently discard the edit.
		f["docs/generated/inventory.md"] = strings.Replace(
			f["docs/generated/inventory.md"],
			"- shipping\n",
			"- shipping\n- reporting  <!-- added manually, gen-inventory does not know about this -->\n", 1)
		return "docs/generated/inventory.md is marked do-not-edit but carries a hand-added entry the generator will discard",
			"docs: add reporting to the inventory"
	},

	DefectCrossDomainLeakage: func(f map[string]string) (string, string) {
		// shipping bypasses billing's published surface and calls its internal.
		f["shipping/shipping.go"] = `package shipping

import "example.com/eval/billing"

// Ship charges the account directly.
func Ship(account string, weight int) int {
	return billing.Charge(account, weight*2)
}
`
		return "shipping calls billing.Charge, bypassing billing.Quote, the published surface it is required to use",
			"shipping: call billing directly to avoid an extra hop"
	},

	DefectIncompleteProofDischarge: func(f map[string]string) (string, string) {
		// The obligation stays "discharged" while its proof reports a failure.
		f["evidence/rate_limit_test_report.txt"] = "rate limit suite: 3 passed, 1 FAILED\n"
		return "obligation.rate_limit_enforced is recorded as discharged while its cited proof reports a failing test",
			"evidence: refresh the rate-limit report"
	},
}

// witnesses independently confirm a defect's presence by reading the tree.
var witnesses = map[Defect]Witness{

	DefectAuthoritySplit: func(root string) (bool, string, error) {
		api, err := readFile(root, "api/api.go")
		if err != nil {
			return false, "", err
		}
		svc, err := readFile(root, "service/service.go")
		if err != nil {
			return false, "", err
		}
		// Two independent computations of the same decision: api must both
		// define its own limit AND disagree with service's value.
		apiComputes := contains(api, "func localLimit(")
		svcPremium := contains(svc, "return 1000")
		apiPremium := contains(api, "return 500")
		if apiComputes && svcPremium && apiPremium {
			return true, "api.localLimit returns 500 for premium where service.RateLimit returns 1000", nil
		}
		return false, "only service computes the rate limit", nil
	},

	DefectForbiddenDependencyDirection: func(root string) (bool, string, error) {
		storage, err := readFile(root, "storage/storage.go")
		if err != nil {
			return false, "", err
		}
		if contains(storage, `"example.com/eval/service"`) {
			return true, "storage imports service", nil
		}
		return false, "storage imports nothing above it", nil
	},

	DefectStaleDocumentation: func(root string) (bool, string, error) {
		doc, err := readFile(root, "docs/ARCHITECTURE.md")
		if err != nil {
			return false, "", err
		}
		svc, err := readFile(root, "service/service.go")
		if err != nil {
			return false, "", err
		}
		// The document asserts a specific ceiling; read what the code returns
		// and compare. The contradiction is the defect, not either half.
		claims1000 := contains(doc, "The premium ceiling is 1000 and has never changed.")
		code2500 := contains(svc, "return 2500")
		if claims1000 && code2500 {
			return true, "the document states 1000, the code returns 2500", nil
		}
		return false, "documentation and code agree on the premium ceiling", nil
	},

	DefectImplementationRepetition: func(root string) (bool, string, error) {
		var copies []string
		for _, p := range []string{"api/api.go", "service/service.go", "storage/storage.go"} {
			body, err := readFile(root, p)
			if err != nil {
				return false, "", err
			}
			if contains(body, "func clamp(v, max int) int {") {
				copies = append(copies, p)
			}
		}
		if len(copies) >= 3 {
			return true, fmt.Sprintf("clamp is duplicated in %s", strings.Join(copies, ", ")), nil
		}
		return false, "clamp appears at most twice", nil
	},

	DefectMissingEvidenceProvider: func(root string) (bool, string, error) {
		claims, err := readFile(root, "docs/claims.md")
		if err != nil {
			return false, "", err
		}
		const cited = "evidence/rate_limit_test_report.txt"
		if !contains(claims, cited) {
			return false, "no claim cites that evidence", nil
		}
		if _, err := os.Stat(filepath.Join(root, filepath.FromSlash(cited))); os.IsNotExist(err) {
			return true, "a claim cites " + cited + ", which is absent", nil
		} else if err != nil {
			return false, "", err
		}
		return false, "the cited evidence exists", nil
	},

	DefectMisleadingCommitMessage: func(root string) (bool, string, error) {
		// The message lives outside the tree, so the witness reads the change
		// the message describes: a security fix would alter behaviour, and a
		// rename does not.
		storage, err := readFile(root, "storage/storage.go")
		if err != nil {
			return false, "", err
		}
		renamedOnly := contains(storage, "func TierOf(id string) string {") && contains(storage, "userID := id")
		if renamedOnly {
			return true, "the only change is a parameter rename; no authentication logic exists to have been fixed", nil
		}
		return false, "no rename-only change present", nil
	},

	DefectGeneratedFileContamination: func(root string) (bool, string, error) {
		gen, err := readFile(root, "docs/generated/inventory.md")
		if err != nil {
			return false, "", err
		}
		if !contains(gen, "GENERATED by") {
			return false, "the file does not declare itself generated", nil
		}
		if contains(gen, "added manually") {
			return true, "a do-not-edit generated file carries a hand-added entry", nil
		}
		return false, "the generated file carries only generated content", nil
	},

	DefectCrossDomainLeakage: func(root string) (bool, string, error) {
		ship, err := readFile(root, "shipping/shipping.go")
		if err != nil {
			return false, "", err
		}
		if contains(ship, "billing.Charge(") && !contains(ship, "billing.Quote(") {
			return true, "shipping calls billing.Charge instead of billing.Quote", nil
		}
		return false, "shipping uses billing's published surface", nil
	},

	DefectIncompleteProofDischarge: func(root string) (bool, string, error) {
		obligations, err := readFile(root, "docs/obligations.md")
		if err != nil {
			return false, "", err
		}
		if !contains(obligations, "status: discharged") {
			return false, "no obligation claims to be discharged", nil
		}
		proof, err := readFile(root, "evidence/rate_limit_test_report.txt")
		if err != nil {
			// Absent proof is the missing-evidence defect, not this one; a
			// witness that claimed both would make the two indistinguishable.
			return false, "the cited proof is absent, which is a different defect", nil
		}
		if contains(proof, "FAILED") {
			return true, "an obligation is discharged while its proof reports a failure", nil
		}
		return false, "the discharged obligation's proof passes", nil
	},
}
